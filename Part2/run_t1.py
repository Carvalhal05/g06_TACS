"""Run T1 and the classical baseline on every test instance.

For each instance of instances.py:
  1. T1 turns the Problem DSL model into a Solution DSL model (CNF + SolverConfig);
  2. the model is written as B-UML Python code by BESSER's own code builder (project_to_code) to
     generated/<instance>_<formula name>.py, which is the input for T2; it is reloaded and compared
     with the in-memory model;
  3. the classical baseline counts the solutions twice (on the CNF and directly on the feature model).
The results (clause trace, solutions, Grover parameters) go to generated/T1_report.md.

    python run_t1.py [shots]      (default shots: 1024)

The files in generated/ are produced by this script and must not be edited by hand.
"""

import runpy
import sys
from pathlib import Path

from besser.BUML.metamodel.object import ObjectModel
from besser.BUML.metamodel.project import Project
from besser.BUML.metamodel.structural.structural import Metadata
from besser.utilities.buml_code_builder.project_builder import project_to_code

import metamodels as mm
from metamodels import attr, objects_of
import baseline
import instances
import t1_problem_to_cnf as t1

OUT = Path(__file__).resolve().parent / "generated"


def load_solution_model(path):
    """The Solution DSL object model stored in a generated B-UML file."""
    models = [v for v in runpy.run_path(str(path)).values() if isinstance(v, ObjectModel)]
    (model,) = models
    return model


def signature(model):
    """Content of a Solution DSL model in a fixed order: variables, clauses, SolverConfig."""
    (cfg,) = objects_of(model, mm.SolverConfig)
    (cnf,) = objects_of(model, mm.CnfFormula)
    return (attr(cnf, "name"), baseline.read_cnf(model),
            tuple(attr(cfg, a) for a in ("knownSolutions", "rounds", "shots")))


def write_generated(solution, path, title, description):
    """Write `solution` with BESSER's code builder, unless `path` already holds the same model.

    The builder writes the links in set order, which changes from run to run; skipping unchanged
    models keeps the generated files stable.
    """
    if path.exists() and signature(load_solution_model(path)) == signature(solution):
        return False
    project = Project(name=title, models=[mm.solution_dsl, solution], owner="g06",
                      metadata=Metadata(description=description))
    project_to_code(project, str(path))
    if signature(load_solution_model(path)) != signature(solution):
        raise RuntimeError(f"{path.name}: reloaded model differs from the T1 output")
    return True


def run(shots=1024):
    OUT.mkdir(exist_ok=True)
    summary, sections = [], []
    for inst, (desc, problem, request) in instances.all_instances().items():
        solution, trace = t1.transform(problem, shots=shots, request_name=request)
        (cnf,) = objects_of(solution, mm.CnfFormula)
        (cfg,) = objects_of(solution, mm.SolverConfig)
        name = attr(cnf, "name")

        path = OUT / f"{inst}_{name}.py"
        write_generated(solution, path, f"{inst}_{name}", f"T1 output for test instance {inst}")

        names, clauses = baseline.read_cnf(solution)
        n, m = len(names), len(clauses)
        sols_cnf = baseline.cnf_solutions(solution)
        sols_fm = baseline.feature_model_configurations(problem, request)
        if sols_cnf != sols_fm:
            raise RuntimeError(f"{inst}: CNF solutions differ from the feature model semantics")
        k, big_m = attr(cfg, "rounds"), attr(cfg, "knownSolutions")
        p = baseline.success_probability(n, big_m, k)
        summary.append(f"| {inst} | {desc} | {n} | {m} | {len(sols_cnf)} | {len(sols_fm)} | {k} | {p:.3f} "
                       f"| {n + m + 1} | `{path.name}` |")

        sec = [f"## {inst} · {name}", "", desc, "",
               "Variables (index = qubit): " + ", ".join(f"{i} {v}" for i, v in enumerate(names)), "",
               f"SolverConfig: knownSolutions = {big_m}, rounds = {k}, shots = {attr(cfg, 'shots')}", "",
               "| Clause | Literals | T1 rule | Source elements | Reference |", "|---|---|---|---|---|"]
        sec += [f"| {t['clause']} | {t['text']} | {t['rule']} | {t['source']} | {t['ref']} |" for t in trace]
        sec += ["", f"Valid configurations ({len(sols_cnf)}):", ""]
        sec += [f"- {', '.join(sorted(s, key=names.index))}" for s in sorted(sols_cnf, key=sorted)] or ["- none"]
        sections.append("\n".join(sec) + "\n")

    report = [
        "# T1 output and classical baseline",
        "",
        "Generated by `run_t1.py`; do not edit by hand.",
        "",
        "M (CNF) is counted by brute force on the CNF produced by T1; M (FM) is counted directly on the",
        "feature model with the semantics of each construct, without the CNF. The two must agree.",
        "Rounds = ⌊π/4 · √(2ⁿ/M)⌋ (Boyer et al., 1998), 1 when M = 0. P(success) = sin²((2k+1)θ),",
        "sin²θ = M/2ⁿ. n + m + 1 is the qubit count with one ancilla per clause plus the output qubit.",
        "",
        "| Instance | Description | n | m | M (CNF) | M (FM) | Rounds k | P(success) | n + m + 1 | T1 output |",
        "|---|---|---|---|---|---|---|---|---|---|",
        *summary,
        "",
        *sections,
    ]
    (OUT / "T1_report.md").write_text("\n".join(report), encoding="utf-8")
    return summary


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    for row in run(int(sys.argv[1]) if len(sys.argv) > 1 else 1024):
        print(row)
    print(f"written to {OUT}")
